#!/usr/bin/env python3
"""Packs the in-app web editor (app/build_app_web.py output) into WebAssets.java, gzip + base64,
so the patch adds no resources and the files live in the editor's own extension.

Usage: gen_web_assets.py <app_web_dir> <WebAssets.java>
"""
import base64
import gzip
import sys
from pathlib import Path

src, out = Path(sys.argv[1]), Path(sys.argv[2])
CHUNK = 60000  # under the 65535-byte limit of one class-file string constant
entries = []
for f in sorted(p for p in src.rglob("*") if p.is_file() and not p.name.startswith(".")):  # skip tool markers
    rel = f.relative_to(src).as_posix()
    data = base64.b64encode(gzip.compress(f.read_bytes(), 9, mtime=0)).decode("ascii")
    parts = [data[i:i + CHUNK] for i in range(0, len(data), CHUNK)]
    entries.append((rel, parts))

methods = []
puts = []
for i, (rel, parts) in enumerate(entries):
    body = ",\n                ".join(f'"{p}"' for p in parts)
    methods.append(f"""    private static String[] f{i}() {{
        return new String[]{{
                {body}
        }};
    }}
""")
    puts.append(f'        FILES.put("{rel}", f{i}());')

out.write_text(f"""/*
 * Generated by editor/app/gen_web_assets.py from the in-app web editor. Do not edit by hand.
 */

package app.morphe.extension.youtube.visualeditor;

import java.util.HashMap;
import java.util.Map;

final class WebAssets {{
    /** Path -> gzip, base64, split in parts. */
    static final Map<String, String[]> FILES = new HashMap<>();

    static {{
{chr(10).join(puts)}
    }}

{chr(10).join(methods)}
    private WebAssets() {{
    }}
}}
""", encoding="utf-8")
total = sum(len(''.join(p)) for _, p in entries)
print(f"{len(entries)} files, {total} base64 chars -> {out}")
